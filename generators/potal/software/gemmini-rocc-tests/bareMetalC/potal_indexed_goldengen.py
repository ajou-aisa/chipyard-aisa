#!/usr/bin/env python3
"""Generate exact, full-density H2-1 golden reference tables on the host.

Matches potal_shared_weight_indexed.c, checkpoint db5e7e52, including
both residual phases and active-K permutation. No third-party packages.
Usage:
  python3 potal_indexed_goldengen.py --dim 64 --out bareMetalC/
  python3 potal_indexed_goldengen.py --all --out bareMetalC/
"""
import argparse
from pathlib import Path


def signed_a(phase: int, i: int, k: int) -> int:
    v = (i * 11 + k * 5 + phase * 17) % 7 - 3
    return (1 if phase else -1) if v == 0 else v


def signed_b(k: int, n: int) -> int:
    v = (k * 37 + n * 13 + (k ^ n) * 7) % 15 - 7
    return 1 if v == 0 else v


def calculate_golden(dim: int):
    krows, ncols, active_r = 3 * dim, 2 * dim, 3 * dim // 2
    active_k = [2 * ((t * 5) % active_r) + 1 for t in range(active_r)]
    # In this test, K=3*DIM and R=3*DIM/2. The active list contains
    # a permutation of all odd original K indices and is in bounds.
    assert len(set(active_k)) == active_r
    assert all(0 <= k < krows for k in active_k)

    # Pre-generate B exactly as the C test does, before its DRAM poison.
    b = [[signed_b(k, n) for n in range(ncols)] for k in range(krows)]
    table = []
    for phase in range(3):
        source = list(range(krows)) if phase == 0 else active_k
        a = [[signed_a(phase, i, t) for t in range(len(source))]
             for i in range(dim)]
        phase_expected = []
        for i in range(dim):
            row = []
            for n in range(ncols):
                total = sum(a[i][t] * b[source[t]][n]
                            for t in range(len(source)))
                # The test uses saturated INT32 ACC and identity SCU shifts.
                total = min(2**31 - 1, max(-2**31, total))
                row.append(total)
            phase_expected.append(row)
        table.append(phase_expected)
    return table


def generate(dim: int, out_dir: Path):
    if dim not in (16, 32, 64):
        raise ValueError('Only DIM16/DIM32/DIM64 are supported by the H2 test')
    data = calculate_golden(dim)
    out_dir.mkdir(parents=True, exist_ok=True)
    target = out_dir / f'potal_indexed_golden_d{dim}.h'
    lines = [
        f'/* Generated by potal_indexed_goldengen.py, DIM={dim}. */',
        '/* Generated offline: no CPU dot products inside Verilator. */',
        f'#define POTAL_GOLDEN_DIM {dim}',
        'static const int32_t potal_golden_reference[PHASES][DIM][NCOLS] = {',
    ]
    for phase, matrix in enumerate(data):
        lines.append(f'  {{ /* phase {phase} */')
        for i, row in enumerate(matrix):
            values = ', '.join(str(x) for x in row)
            lines.append(f'    {{ {values} }}{"," if i < dim - 1 else ""}')
        lines.append('  }' + (',' if phase != 2 else ''))
    lines.extend(['};', ''])
    target.write_text('\n'.join(lines), encoding='ascii')
    total_bytes = target.stat().st_size
    print(f'{target}: {total_bytes} bytes, {3 * dim * (2 * dim)} expected values')
    return target


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument('--dim', type=int, choices=[16, 32, 64])
    group.add_argument('--all', action='store_true')
    parser.add_argument('--out', type=Path, default=Path('.'),
                        help='Destination directory, typically bareMetalC/')
    args = parser.parse_args()
    for dim in ([16, 32, 64] if args.all else [args.dim]):
        generate(dim, args.out)


if __name__ == '__main__':
    main()
