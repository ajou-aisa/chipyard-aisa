#!/usr/bin/env python3
"""Generate H2-2A full-ACC golden checkpoints for DIM16/32/64.

Works with potal_shared_weight_multiwindow.c and requires no packages.
Usage: python3 bareMetalC/potal_multiwindow_goldengen.py --all --out bareMetalC
"""
import argparse
from math import gcd
from pathlib import Path


def aval(phase: int, i: int, t: int) -> int:
    v = (i * 11 + t * 5 + phase * 17) % 7 - 3
    return (1 if phase else -1) if v == 0 else v


def bval(k: int, n: int) -> int:
    v = (k * 37 + n * 13 + (k ^ n) * 7) % 15 - 7
    return 1 if v == 0 else v


def sat32(x: int) -> int:
    return max(-(1 << 31), min((1 << 31) - 1, x))


def golden(dim: int) -> list:
    krows, ncols, active = 3 * dim, 2 * dim, 5 * dim // 2
    cap = 2 * dim  # Expected current RTL index window size.
    assert gcd(7, krows) == 1
    src = [(7 * t + 5) % krows for t in range(active)]
    assert len(set(src)) == active and active > cap
    b = [[bval(k, n) for n in range(ncols)] for k in range(krows)]

    # Expected checkpoints after MAIN, R1 W0, R1 W1, R2 W0, R2 W1.
    main = [[sat32(sum(aval(0, i, k) * b[k][n]
                        for k in range(krows))) for n in range(ncols)]
            for i in range(dim)]
    current = [[0] * ncols for _ in range(dim)]
    snapshots = [main]
    for phase in (1, 2):
        for first in (0, cap):
            rows = min(cap, active - first)
            for i in range(dim):
                for n in range(ncols):
                    delta = sum(aval(phase, i, t) * b[src[t]][n]
                                for t in range(first, first + rows))
                    current[i][n] = sat32(current[i][n] + delta)
            snapshots.append([row[:] for row in current])
    assert len(snapshots) == 5
    return snapshots


def emit(dim: int, output: Path) -> None:
    data = golden(dim)
    target = output / f'potal_multiwindow_golden_d{dim}.h'
    lines = [
        '/* Generated by potal_multiwindow_goldengen.py; do not edit. */',
        f'#define POTAL_MW_GOLDEN_DIM {dim}',
        '#define POTAL_MW_GOLDEN_STEPS 5',
        'static const int32_t potal_multiwindow_golden[5][DIM][NCOLS] = {',
    ]
    for step, matrix in enumerate(data):
        lines.append(f'  {{ /* checkpoint {step} */')
        for i, row in enumerate(matrix):
            lines.append('    {' + ', '.join(str(n) for n in row) +
                         '}' + (',' if i + 1 != dim else ''))
        lines.append('  }' + (',' if step < 4 else ''))
    lines += ['};', '']
    output.mkdir(parents=True, exist_ok=True)
    target.write_text('\n'.join(lines), encoding='ascii')
    print(f'{target}: {target.stat().st_size} bytes / 5 x {dim} x {2*dim} entries')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument('--all', action='store_true')
    group.add_argument('--dim', type=int, choices=[16, 32, 64])
    parser.add_argument('--out', type=Path, default=Path('bareMetalC'))
    opts = parser.parse_args()
    for dim in ([16, 32, 64] if opts.all else [opts.dim]):
        emit(dim, opts.out)


if __name__ == '__main__':
    main()

